#!/usr/bin/env python3
"""Report implementation SLOC only: omit blanks, comment-only lines and docstrings.
Imports, declarations and syntax delimiters count. Tests, docs, generators,
route catalogs, dependency manifests and build output do not count.
"""
from __future__ import annotations
import ast
import io
import json
import tokenize
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def code_lines(path):
    source = path.read_text()
    if path.suffix == '.py':
        doclines = set()
        for node in ast.walk(ast.parse(source)):
            body = getattr(node, 'body', None)
            if isinstance(body, list) and body and isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant) and isinstance(body[0].value.value, str):
                doclines.update(range(body[0].lineno, body[0].end_lineno + 1))
        ignored = {tokenize.COMMENT, tokenize.NL, tokenize.NEWLINE, tokenize.INDENT, tokenize.DEDENT, tokenize.ENDMARKER, tokenize.ENCODING}
        lines = set()
        for token in tokenize.generate_tokens(io.StringIO(source).readline):
            if token.type not in ignored:
                lines.update(range(token.start[0], token.end[0] + 1))
        return len(lines - doclines)
    # All production Go/TS/Rust comments in these SDKs use // syntax. Fail
    # explicitly if block comments appear so this report cannot silently count
    # future multiline commentary as implementation.
    if '/*' in source or '*/' in source:
        raise ValueError(f'block comments require updating the source counter: {path}')
    return sum(bool(line.strip()) and not line.lstrip().startswith('//') for line in source.splitlines())


def main():
    groups = {
        'Go': sorted((ROOT / 'sdks/go/zakura').glob('*.go')),
        'TypeScript': sorted((ROOT / 'sdks/typescript/src').rglob('*.ts')),
        'Python': sorted((ROOT / 'sdks/python/zakura_sdk').rglob('*.py')),
        'Rust': sorted((ROOT / 'sdks/rust/src').rglob('*.rs')),
    }
    report = {}
    for language, paths in groups.items():
        result = {'handwritten': 0, 'generated_implementation': 0, 'total': 0, 'files': 0}
        for path in paths:
            if path.name.endswith('_test.go'):
                continue
            count = code_lines(path)
            key = 'generated_implementation' if 'Code generated by scripts/sdk/generate.py;' in path.read_text()[:300] else 'handwritten'
            result[key] += count
            result['total'] += count
            result['files'] += 1
        report[language] = result
    report['total'] = sum(row['total'] for row in report.values())
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
